// Static smoke test for MediQueue using a minimal DOM host (no npm dependencies).
import assert from 'node:assert/strict';
const mem=new Map();
const store={getItem:k=>mem.get(k)||null,setItem:(k,v)=>mem.set(k,String(v)),removeItem:k=>mem.delete(k)};
globalThis.localStorage=store;globalThis.sessionStorage=store;
globalThis.window={addEventListener:()=>{},scrollTo:()=>{}};
Object.defineProperty(globalThis,'navigator',{value:{clipboard:{writeText:async()=>{}}},configurable:true});
globalThis.BroadcastChannel=class { constructor(){} postMessage(){} };
globalThis.setInterval=()=>0;globalThis.setTimeout=()=>0;
let html='';const handlers={};
globalThis.document={hidden:false,createElement:()=>({className:'',innerHTML:'',remove(){}}),getElementById:(id)=>id==='app'?{set innerHTML(s){html=s},get innerHTML(){return html}}:id==='toasts'?{append(){}}:null,addEventListener:(event,fn)=>{handlers[event]=fn}};
globalThis.FormData=class {constructor(form){this.form=form;}get(n){return this.form.data[n];}};
await import('../app.js');
assert.match(html,/Chào mừng trở lại/);
assert.match(html,/Khám tổng quát/);
assert.match(html,/MediQueue/);
const nav=async page=>{const target={matches:()=>false,closest:(sel)=>sel==='[data-page]'?{dataset:{page}}:null};await handlers.click({target});};
const act=async (action,attrs={})=>{const target={closest:(sel)=>sel==='[data-action]'?{dataset:{action,...attrs}}:null,matches:()=>false};await handlers.click({target});};
await nav('reception');assert.match(html,/Quầy tiếp đón/);assert.doesNotMatch(html,/Minh Anh/); // Patient cannot access staff list.
await nav('book');assert.match(html,/Đăng ký lấy số/);
await handlers.submit({preventDefault(){},target:{id:'bookingForm',data:{patientName:'Người Demo',department:'GENERAL'}}});
assert.match(html,/Theo dõi lượt khám/);
assert.match(html,/T011/);
await nav('staff');assert.match(html,/Khu vực dành cho nhân viên/);
await act('demo-staff');assert.match(html,/Quản lý phòng khám/);
assert.match(html,/Phòng 101/);
await nav('reception'); assert.match(html,/Quầy tiếp đón/);
assert.match(html,/Danh sách lượt khám/);
await nav('board'); assert.match(html,/Bảng theo dõi khu chờ/);
assert.match(html,/ĐANG GỌI/);
assert.doesNotMatch(html,/Minh Anh/); // Do not expose patient names on public display.
await nav('guide'); assert.match(html,/Hướng dẫn sử dụng/);
await nav('staff');
// A patient code can be checked in only from the staff workflow.
const ownerBefore=JSON.parse(mem.get('mediqueue_web_demo_v1')).tickets.find(t=>t.patient_id==='demo-me' && t.queue_number===11);
assert.equal(ownerBefore.checked_in_at,null);
await act('checkin-form');
assert.match(html,/Nhập mã nhận từ chính bệnh nhân/);
await handlers.submit({preventDefault(){},target:{id:'checkinForm',data:{nonce:ownerBefore.qr_nonce}}});
const checked=JSON.parse(mem.get('mediqueue_web_demo_v1')).tickets.find(t=>t.id===ownerBefore.id);
assert.ok(checked.checked_in_at && checked.room_id);
await nav('analytics');assert.match(html,/Phân tích hoạt động/);
await nav('account');assert.match(html,/Chế độ demo/);
await act('demo-patient');
await nav('track');
await act('cancel',{id:String(ownerBefore.id)});
assert.match(html,/Hủy phiếu/);
await act('confirm-modal');
const canceled=JSON.parse(mem.get('mediqueue_web_demo_v1')).tickets.find(t=>t.id===ownerBefore.id);
assert.equal(canceled.status,'SKIPPED');
console.log('MediQueue smoke test: PASS (home, booking, reception, privacy-safe TV board, guide, staff, analytics, account)');
